import os
import glob

import pandas as pd
import matplotlib.pyplot as plt


# ---------------------------------------------------------
# 1. PROJECT PATHS
# ---------------------------------------------------------

PROJECT_PATH = "/mnt/d/sem7/BigData/Big data project"

OUTPUT_PATH = os.path.join(PROJECT_PATH, "output")
VIZ_PATH = os.path.join(OUTPUT_PATH, "visualizations")


# Create visualization directory
os.makedirs(VIZ_PATH, exist_ok=True)


# ---------------------------------------------------------
# 2. HELPER FUNCTION
# ---------------------------------------------------------

def read_spark_csv(folder_name):
    """
    Reads the CSV part generated by Spark.
    """

    folder_path = os.path.join(OUTPUT_PATH, folder_name)

    csv_files = glob.glob(
        os.path.join(folder_path, "part-*.csv")
    )

    if not csv_files:
        raise FileNotFoundError(
            f"No Spark CSV file found in {folder_path}"
        )

    return pd.read_csv(csv_files[0])


# ---------------------------------------------------------
# 3. LOAD ANALYSIS RESULTS
# ---------------------------------------------------------

rating_distribution = read_spark_csv(
    "rating_distribution"
)

most_rated_movies = read_spark_csv(
    "most_rated_movies"
)

highest_rated_movies = read_spark_csv(
    "highest_rated_movies"
)


print("\n" + "=" * 65)
print("             MOVIE RECOMMENDATION VISUALIZATION")
print("=" * 65)


# ---------------------------------------------------------
# 4. RATING DISTRIBUTION
# ---------------------------------------------------------

plt.figure(figsize=(9, 6))

plt.bar(
    rating_distribution["Rating"].astype(str),
    rating_distribution["RatingCount"]
)

plt.title("MovieLens Rating Distribution")
plt.xlabel("Rating")
plt.ylabel("Number of Ratings")

plt.tight_layout()

rating_plot = os.path.join(
    VIZ_PATH,
    "rating_distribution.png"
)

plt.savefig(rating_plot, dpi=300)

plt.close()

print("\nCreated:")
print(rating_plot)


# ---------------------------------------------------------
# 5. MOST RATED MOVIES
# ---------------------------------------------------------

top_most_rated = (
    most_rated_movies
    .sort_values(
        "RatingCount",
        ascending=False
    )
    .head(10)
    .sort_values(
        "RatingCount"
    )
)

plt.figure(figsize=(10, 7))

plt.barh(
    top_most_rated["Title"],
    top_most_rated["RatingCount"]
)

plt.title("Top 10 Most Rated Movies")
plt.xlabel("Number of Ratings")
plt.ylabel("Movie")

plt.tight_layout()

most_rated_plot = os.path.join(
    VIZ_PATH,
    "most_rated_movies.png"
)

plt.savefig(
    most_rated_plot,
    dpi=300,
    bbox_inches="tight"
)

plt.close()

print("Created:")
print(most_rated_plot)


# ---------------------------------------------------------
# 6. HIGHEST-RATED MOVIES
# ---------------------------------------------------------

top_highest_rated = (
    highest_rated_movies
    .sort_values(
        "AverageRating",
        ascending=False
    )
    .head(10)
    .sort_values(
        "AverageRating"
    )
)

plt.figure(figsize=(10, 7))

plt.barh(
    top_highest_rated["Title"],
    top_highest_rated["AverageRating"]
)

plt.title(
    "Top 10 Highest-Rated Movies "
    "(Minimum 100 Ratings)"
)

plt.xlabel("Average Rating")
plt.ylabel("Movie")

plt.xlim(0, 5)

plt.tight_layout()

highest_rated_plot = os.path.join(
    VIZ_PATH,
    "highest_rated_movies.png"
)

plt.savefig(
    highest_rated_plot,
    dpi=300,
    bbox_inches="tight"
)

plt.close()

print("Created:")
print(highest_rated_plot)


# ---------------------------------------------------------
# 7. COMPLETION
# ---------------------------------------------------------

print("\n" + "=" * 65)
print("             VISUALIZATIONS COMPLETED")
print("=" * 65)

print("\nCharts saved in:")
print(VIZ_PATH)

print("\nGenerated charts:")
print("1. rating_distribution.png")
print("2. most_rated_movies.png")
print("3. highest_rated_movies.png")